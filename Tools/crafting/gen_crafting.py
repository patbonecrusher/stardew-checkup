P = '/Users/pat/Projects/stardewvalley-checker/Sources/StardewCheckup/Parsing/'
cd = open(P + 'CollectionData.swift').read()
blk = cd[cd.find('static let craftingRecipes'):]; blk = blk[blk.find('= ['):]; blk = blk[:blk.find(']')]
names = re.findall(r'"([^"]+)"', blk)
col = open(P + 'Sections/Collections.swift').read()
f = col[col.find('func parseCrafting'):col.find('let recipeSet')]
for l in re.findall(r'recipes \+= \[(.*?)\]', f): names += re.findall(r'"([^"]+)"', l)
print('missing:', [n for n in names if n not in seen])
print('extra:', sorted(seen - set(names)))

# Ingredients that are not concrete item names (category placeholders like "Any Fish").
ingredients = sorted({n for r in recipes for n, _ in r['ingredients']})
print('non-concrete ingredients:', [n for n in ingredients if re.match(r'(Any|Every)\b', n) or '(' in n or ' or ' in n])

