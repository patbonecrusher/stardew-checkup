import json, re
recipes = json.load(open('crafting.json'))
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

# Wiki names that differ from the names the app uses (CollectionData.craftingRecipes + parseCrafting additions).
RENAME = {}
SKIP = {'Wedding Ring'}

def app_name(n):
    n = re.sub(r'\s*\(\d+\)$', '', n)                 # yield count, e.g. "Bait (5)"
    n = re.sub(r'\s*\(\s*\w+ Seeds\s*\)$', '', n)    # "Wild Seeds (Sp) ( Spring Seeds )"
    return RENAME.get(n, n)

SHOPS = {
    "Carpenter's Shop": "Robin's shop", "Pierre's": "Pierre's shop", "Purchase from Pierre's": "Pierre's shop",
    "Fish Shop": "Willy's shop", "Volcano Dwarf shop": "Volcano Dungeon dwarf", "Traveling Cart": "Traveling Cart",
}

def source(src):
    s = re.sub(r"\s+'", "'", src)
    s = re.sub(r'\(\s*', '(', s); s = re.sub(r'\s*\)', ')', s)
    if s == 'Starter': return "known from the start"
    m = re.fullmatch(r'(Farming|Fishing|Foraging|Mining|Combat) \(?Level (\d+)\)?', s)
    if m: return f"{m.group(1)} level {m.group(2)}"
    m = re.fullmatch(r'(Farming|Fishing|Foraging|Mining|Combat) Mastery', s)
    if m: return f"Mastery: {m.group(1)}"
    m = re.fullmatch(r"(.+?) for ([\d,]+g)", s)
    if m and m.group(1) in SHOPS: return f"{SHOPS[m.group(1)]} for {m.group(2)}"
    m = re.fullmatch(r"(Krobus|Krobus' Shop|Dwarf) \(([\d,]+g)\)", s)
    if m: return f"{'Krobus' if 'Krobus' in m.group(1) else 'Dwarf in the Mines'} for {m.group(2)}"
    m = re.fullmatch(r"Pierre's stand at (Flower Dance|Spirit's Eve) (?:festival )?\(([\d,]+g)\)", s)
    if m:
        fest = m.group(1) + (' festival' if m.group(1) == "Spirit's Eve" else '')
        return f"Pierre's booth at the {fest} for {m.group(2)}"
    m = re.fullmatch(r"(?:Purchase from Mr Qi|Qi's Walnut Room) for (\d+)", s)
    if m: return f"Qi's Walnut Room for {m.group(1)} Qi Gems"
    m = re.fullmatch(r"(?:Purchase from )?(Island|Desert) Trader for (.+?) \((\d+)\)", s)
    if m: return f"{m.group(1)} Trader for {m.group(3)} {m.group(2)}s"
    m = re.fullmatch(r"(\w+) (?:\(Special Order\)|special order)", s)
    if m: return f"{m.group(1)}'s special order"
    m = re.fullmatch(r"(\w+) \(Mail - (\d+)\+\)", s)
    if m: return f"letter from {m.group(1)} at {m.group(2)}+ hearts"
    m = re.fullmatch(r"(\w+) (\d+)-[Hh]eart [Ee]vent", s)
    if m: return f"{m.group(1)}'s {m.group(2)}-heart event"
    m = re.fullmatch(r"Mail the day after (\w+)'s (\d+)-heart event", s)
    if m: return f"letter after {m.group(1)}'s {m.group(2)}-heart event"
    fixed = {
        'Clint (Morning after collecting 1+ Copper Ore)': "Clint, the day after first picking up Copper Ore",
        'Mail the day after collecting all rarecrows': "letter after finding all 8 Rarecrows",
        'Complete the Island Field Office Collection': "finishing the Island Field Office collections",
        'Donating Ancient Seed to museum': "donating an Ancient Seed to the museum",
        'Evelyn cutscene after completing the Greenhouse': "Evelyn, once the Greenhouse is repaired",
        'Farmhouse cellar upgrade': "the cellar house upgrade",
        "The Pirate's Wife Quest": "reward for the Pirate's Wife quest",
    }
    if s in fixed: return fixed[s]
    print('UNCLASSIFIED source:', repr(src))
    return s

lines, seen = [], set()
for r in recipes:
    name = app_name(r['name'])
    if name in SKIP: continue
    seen.add(name)
    ings = ', '.join(f'({q(n)}, {c})' for n, c in r['ingredients'])
    lines.append(f'        CraftingRecipe(name: {q(name)}, ingredients: [{ings}], source: {q(source(r["source"]))}),')

