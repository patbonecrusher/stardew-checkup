# Turn crops.json (from parse_crops.py) into Sources/StardewCheckup/Parsing/CropData.swift.
import json, re
crops = json.load(open('crops.json'))
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

SHOP = {"Pierre's": "Pierre's", "JojaMart": "JojaMart", "Oasis": "Sandy's Oasis", "Egg Festival": "Egg Festival",
        "Traveling Cart": "Traveling Cart"}

def source(c):
    if 'raccoon' in c:
        n, item = c['raccoon']
        if n > 1 and item not in ('Sap', 'Moss'): item += 's'
        return f"no shop; Seed Spots, Mystery Boxes, or the Raccoon Wife's shop for {n} {item}"
    parts = []
    for piece in c['source_raw'].split(' / '):
        m = re.fullmatch(r"(.+?) : ([\d,]+g)", piece)
        if m and m.group(1) in SHOP:
            parts.append(f"{SHOP[m.group(1)]}, {m.group(2)}"); continue
        m = re.fullmatch(r"Island Trader : (.+?) \((\d+)\)", piece)
        if m:
            n, item = int(m.group(2)), m.group(1)
            parts.append(f"Island Trader, {n} {item}{'s' if n > 1 else ''}"); continue
        if piece == 'Crafting Recipe : Free':
            parts.append("craft for free (recipe from Gunther after donating an Ancient Seed)"); continue
        m = re.fullmatch(r"Dust Sprite \((.+?) chance\)", piece)
        if m:
            parts.append(f"Dust Sprites drop it ({m.group(1)})"); continue
        raise SystemExit(f"unhandled source piece for {c['name']}: {piece!r}")
    return '; '.join(parts)

lines = []
for c in crops:
    seasons = ', '.join(q(s) for s in c['seasons'])
    lines.append(f'        CropInfo(name: {q(c["name"])}, seed: {q(c["seed"])}, seasons: [{seasons}], '
                 f'days: {c["days"]}, regrow: {c["regrow"]}, source: {q(source(c))}),')

out = '''import Foundation

/// Crop growing facts (seed, seasons, days to first harvest, regrowth) for the Polyculture and Monoculture
/// crops plus a few extras. Facts compiled from the Stardew Valley Wiki (Crops page and individual crop/seed
/// pages, CC BY-NC-SA 3.0), October 2026, game version 1.6; source wording is our own.
/// Generated by Tools/crops/gen_crops.py.
struct CropInfo: Identifiable {
    /// Harvested crop name, as used in CollectionData.polyCrops.
    let name: String
    /// Item that is planted, e.g. "Parsnip Seeds"; Coffee Bean is planted as the bean itself.
    let seed: String
    /// "Spring", "Summer", "Fall" or "Winter".
    let seasons: [String]
    /// Days to first harvest, without fertilizer or professions.
    let days: Int
    /// Days between later harvests; 0 for single-harvest crops.
    let regrow: Int
    /// Where to get the seeds.
    let source: String
    var id: String { name }
}

enum CropData {
    static let all: [CropInfo] = [
''' + '\n'.join(lines) + '''
    ]

    private static let byName: [String: CropInfo] = Dictionary(uniqueKeysWithValues: all.map { ($0.name, $0) })

    static func info(_ name: String) -> CropInfo? { byName[name] }
}
'''
open('/Users/pat/Projects/stardewvalley-checker/Sources/StardewCheckup/Parsing/CropData.swift', 'w').write(out)
