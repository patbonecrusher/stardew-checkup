import json, re
recipes = json.load(open('cooking.json'))
SEASONS = ['Spring', 'Summer', 'Fall', 'Winter']
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
lines = []
for r in recipes:
    parts, tv = [], None
    src = r['source']
    m = re.search(r'The Queen of Sauce; (\d+) (\w+), Year (\d+)', src)
    if m:
        tv = (int(m.group(1)), m.group(2), int(m.group(3)))
        parts.append(f"Queen of Sauce TV show, {m.group(2)} {m.group(1)} of year {m.group(3)}")
        src = src.replace(m.group(0), '')
    for who, h in re.findall(r"([A-Z][\w']+) \(Mail - (\d+)\+ \)", src):
        parts.append(f"letter from {who} at {h}+ hearts")
    for m2 in re.finditer(r'(Stardrop Saloon|Ginger Island Resort|Dwarf Shop in Volcano Dungeon) for ([\d,]+g)', src):
        place = {'Stardrop Saloon': 'Saloon', 'Ginger Island Resort': 'Ginger Island resort', 'Dwarf Shop in Volcano Dungeon': 'Volcano Dungeon dwarf'}[m2.group(1)]
        parts.append(f"buy at the {place} for {m2.group(2)}")
    m3 = re.search(r'(Farming|Fishing|Foraging|Mining|Combat) Level (\d+)', src)
    if m3: parts.append(f"reach {m3.group(1)} level {m3.group(2)}")
    if 'Starter' in src: parts.append("known from the start")
    if 'Island Trader' in src: parts.append("Island Trader, for 30 Bone Fragments")
    if '4-heart event' in src: parts.append("Evelyn's 4-heart event")
    assert parts, r
    ings = ', '.join(f'({q(n)}, {c})' for n, c in r['ingredients'])
    tvs = f'({tv[0]}, {q(tv[1])}, {tv[2]})' if tv else 'nil'
    lines.append(f'        CookingRecipe(name: {q(r["name"])}, ingredients: [{ings}], source: {q("; ".join(parts))}, tv: {tvs}),')
out = '''import Foundation

/// Cooking recipes with ingredients and where to learn them. Facts compiled from the Stardew Valley Wiki
/// (Cooking page, CC BY-NC-SA 3.0), October 2026; source wording is our own.
/// Generated by Tools/cooking/gen_cooking.py.
struct CookingRecipe: Identifiable {
    let name: String
    /// (ingredient, count). "Egg", "Milk" and "Any Fish" accept any item of that category.
    let ingredients: [(String, Int)]
    let source: String
    /// Queen of Sauce air date (day, season, year), when the recipe comes from the TV.
    let tv: (Int, String, Int)?
    var id: String { name }
}

enum CookingData {
    static let recipes: [CookingRecipe] = [
''' + '\n'.join(lines) + '''
    ]
}
'''
open('/Users/pat/Projects/stardewvalley-checker/Sources/StardewCheckup/Parsing/CookingData.swift', 'w').write(out)
